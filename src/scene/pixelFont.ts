export const FONT_HEIGHT = 5
const glyph = (ch: string) => ROWS[ch.toUpperCase()] ?? ROWS[' ']!

/** How many pixels wide a line of text is (one pixel between letters). */
export const textWidth = (text: string) => [...text].reduce((w, ch) => w + glyph(ch)[0]!.length + 1, -1)

/** Every lit pixel of a line of text, from its top left: [x, y]. */
export function textPixels(text: string): [number, number][] {
  const out: [number, number][] = []
  let x0 = 0
  for (const ch of text) {
    const rows = glyph(ch)
    rows.forEach((row, y) => [...row].forEach((c, x) => c === '#' && out.push([x0 + x, y])))
    x0 += rows[0]!.length + 1
  }
  return out
}
